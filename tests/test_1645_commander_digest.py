"""card #1645 T1: the published Appendix A vectors (card #1630), not expectations
generated by the implementation. V1 and V3-V6 are verbatim from mesh-gateway's
fixture; V2 stays out of this public file (fold F6) and a neutral needs_sso
vector, V7, takes its place. Each vector is also recomputed with a second
serialiser, the way science-claude did on #5688 and #5691."""
import hashlib
import json
from pathlib import Path

import pytest

pytest.importorskip("fastapi")
import rfc8785  # noqa: E402,F401  plain import: a missing pin fails loudly wherever the extra is installed

from swarph_cli.gateway import commander_queue  # noqa: E402

FIXTURE = Path(__file__).parent / "fixtures/1645_digest_vectors.json"
VECTORS = json.loads(FIXTURE.read_text(encoding="utf-8"))
V2_SHA256 = "98f60c56a46b35d7bf62a750630c341edf3ac4c508d04790e98671e7fee310ac"


@pytest.mark.parametrize("vector", VECTORS, ids=lambda item: item["name"])
def test_published_jcs_bytes_and_digest(vector):
    row = json.loads(vector["canonical"])
    assert commander_queue.canonical_bytes(row["id"], row["type"], row["params"]) == vector["canonical"].encode("utf-8")
    assert commander_queue.digest(row["id"], row["type"], row["params"]) == vector["sha256"]


@pytest.mark.parametrize("vector", VECTORS, ids=lambda item: item["name"])
def test_a_second_serialiser_agrees(vector):
    row = json.loads(vector["canonical"])
    second = json.dumps({"id": row["id"], "type": row["type"], "params": row["params"]},
                        sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    assert second == vector["canonical"].encode("utf-8")
    assert hashlib.sha256(second).hexdigest() == vector["sha256"]


def test_v2_is_absent_and_the_neutral_needs_sso_vector_is_present():
    assert [v["name"] for v in VECTORS] == ["V1", "V3", "V4", "V5", "V6", "V7"]
    assert V2_SHA256 not in FIXTURE.read_text(encoding="utf-8")
    neutral = next(v for v in VECTORS if v["name"] == "V7")
    row = json.loads(neutral["canonical"])
    assert row["type"] == "decision" and row["params"]["needs_sso"] is True
    assert commander_queue.decision_fits(row["params"])
