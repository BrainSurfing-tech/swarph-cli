"""Card #1224. The panel's refresh script: the tap-option port, the row rules, the cache write.

Run: python3 -m unittest discover -s plugins/swarph-panel/tests   (or pytest plugins/swarph-panel/tests)

tap_golden.json holds what the ORIGINAL board-publisher (build_board.py `_tap_options`,
`_tap_closable`; publish_board.py `commander_title`, `untagged_title`) answered for each input. It
was generated by calling the original on synthetic titles shaped like the board's real ones; the
repo is public, so no real row text is committed. A change to the ported code that moves any
answer fails here.
"""
from __future__ import annotations

import importlib.util
import json
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("refresh", HERE.parent / "hooks" / "panel" / "refresh.py")
refresh = importlib.util.module_from_spec(spec)
spec.loader.exec_module(refresh)
GOLDEN = json.loads((HERE / "tap_golden.json").read_text(encoding="utf-8"))


def shape(options):
    return None if options is None else [[o["label"], o["text"], o["outcome"]] for o in options]


class PortMatchesOriginal(unittest.TestCase):
    def test_tap_options_on_every_golden_title(self):
        self.assertGreaterEqual(len(GOLDEN["tap_options"]), 20)
        for case in GOLDEN["tap_options"]:
            with self.subTest(title=case["title"]):
                self.assertEqual(shape(refresh._tap_options({"title": case["title"]})), case["options"])

    def test_golden_covers_yes_no_choices_and_unparsed(self):
        kinds = {
            "none" if c["options"] is None else ("yesno" if [o[1] for o in c["options"]] == ["yes", "no"] else "choices")
            for c in GOLDEN["tap_options"]
        }
        self.assertEqual(kinds, {"none", "yesno", "choices"})

    def test_tap_closable(self):
        for case in GOLDEN["tap_closable"]:
            with self.subTest(case=case):
                self.assertEqual(refresh._tap_closable({"holder": case["holder"], "step": case["step"]}), case["closable"])

    def test_titles(self):
        for case in GOLDEN["titles"]:
            with self.subTest(accept=case["accept"][:40]):
                self.assertEqual(refresh.commander_title(case["accept"]), case["commander_title"])
                self.assertEqual(refresh.untagged_title({"accept": case["accept"], "card_id": 7, "id": 9}), case["untagged_title"])


def obligation(oid, created_at, accept, holder="commander", step=None, card_id=50, status="open"):
    return {"id": oid, "card_id": card_id, "created_at": created_at, "accept": accept, "holder": holder, "step": step, "status": status, "state": status}


class RowRules(unittest.TestCase):
    def test_oldest_first_and_only_the_commanders_open_rows(self):
        rows = [
            obligation(3, "2026-10-19T09:00:00+00:00", "[commander] Third?"),
            obligation(1, "2026-10-19T07:00:00+00:00", "[commander] Extend, flip, or kill? | PASS=x"),
            obligation(2, "2026-10-19T08:00:00+00:00", "[commander] Second?"),
            obligation(4, "2026-10-19T06:00:00+00:00", "[commander] Closed?", status="closed"),
            obligation(5, "2026-10-19T06:30:00+00:00", "PASS = a cell row, not the commander's", holder="lab-ovh"),
        ]
        out = refresh.commander_rows(rows, [])
        self.assertEqual([r["id"] for r in out], [1, 2, 3])
        self.assertEqual([o["label"] for o in out[0]["options"]], ["Extend", "Flip", "Kill"])
        self.assertEqual(set(out[0]), {"id", "card_id", "created_at", "title", "options"})
        self.assertEqual(set(out[0]["options"][0]), {"label", "text", "outcome"})

    def test_an_untagged_commander_row_takes_the_offer_question(self):
        accept = "PASS = commander taps Yes (merge) | FAIL = commander taps No"
        offer = {"to_node": "commander", "content": f"Merge it now?\n\nACCEPT CHECK: {accept}"}
        out = refresh.commander_rows([obligation(9, "2026-10-19T07:00:00+00:00", accept)], [offer])
        self.assertEqual(out[0]["title"], "Merge it now?")
        self.assertEqual([o["label"] for o in out[0]["options"]], ["Yes", "No"])

    def test_no_buttons_when_a_tap_would_close_nothing_or_the_title_does_not_parse(self):
        rows = [
            obligation(1, "2026-10-19T07:00:00+00:00", "[commander] Should we ship or hold the release?"),
            obligation(2, "2026-10-19T07:01:00+00:00", "[commander] Merge it?", holder="lab-ovh", step="plan-review"),
            obligation(3, "2026-10-19T07:02:00+00:00", "[commander] Merge it?", step="validate"),
            obligation(4, "2026-10-19T07:03:00+00:00", "[commander] | PASS = x", card_id=8),
        ]
        out = refresh.commander_rows(rows, [])
        self.assertEqual([r["options"] for r in out], [None, None, None, None])
        self.assertEqual(out[3]["title"], "card #8 row #4")


class FakeCli:
    """Stands in for subprocess.run. Records every argv; answers the two read verbs."""

    def __init__(self, obligations, threads=None, fail=False):
        self.calls, self.obligations, self.threads, self.fail = [], obligations, threads or {}, fail

    def __call__(self, argv, **kw):
        self.calls.append(argv)
        if self.fail:
            return subprocess.CompletedProcess(argv, 1, "", "boom")
        if argv[2:4] == ["obligations", "list"]:
            return subprocess.CompletedProcess(argv, 0, json.dumps({"obligations": self.obligations}), "")
        if argv[2:4] == ["cards", "thread"]:
            return subprocess.CompletedProcess(argv, 0, json.dumps({"messages": self.threads.get(argv[4], [])}), "")
        raise AssertionError(f"unexpected command {argv}")


class RefreshWritesTheCache(unittest.TestCase):
    def setUp(self):
        self.dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.dir.cleanup)
        self.out = Path(self.dir.name) / ".swarph-panel-rows.json"

    def test_writes_rows_and_uses_read_verbs_only(self):
        accept = "PASS = commander taps Yes"
        cli = FakeCli(
            [obligation(2, "2026-10-19T08:00:00+00:00", accept, card_id=77), obligation(1, "2026-10-19T07:00:00+00:00", "[commander] Go?")],
            {"77": [{"to_node": "commander", "content": f"Ship it?\n\nACCEPT CHECK: {accept}"}]},
        )
        cache = refresh.refresh(as_peer="lab-ovh", board_url="https://b.example/", run=cli, out=self.out)
        on_disk = json.loads(self.out.read_text())
        self.assertEqual(on_disk, cache)
        self.assertEqual([r["title"] for r in on_disk["rows"]], ["Go?", "Ship it?"])
        self.assertEqual(on_disk["board_url"], "https://b.example/")
        self.assertEqual(cli.calls[0], ["swarph", "board", "obligations", "list", "--status", "open", "--json", "--as", "lab-ovh"])
        self.assertEqual(cli.calls[1], ["swarph", "board", "cards", "thread", "77", "--json", "--as", "lab-ovh"])
        # Read-only: no write verb, no inbox, no credential path on any command line.
        for argv in cli.calls:
            self.assertEqual(argv[:2], ["swarph", "board"])
            self.assertTrue(set(argv).isdisjoint({"say", "close", "send", "take", "decline", "inbox", "--token-file"}), argv)

    def test_zero_open_rows_is_written_as_zero_rows(self):
        self.out.write_text(json.dumps({"rows": [{"id": 1}]}))
        refresh.refresh(as_peer="lab-ovh", board_url="", run=FakeCli([]), out=self.out)
        self.assertEqual(json.loads(self.out.read_text())["rows"], [])

    def test_a_failed_read_keeps_the_last_cache(self):
        self.out.write_text('{"rows": [{"id": 1}]}')
        with self.assertRaises(RuntimeError):
            refresh.refresh(as_peer="lab-ovh", board_url="", run=FakeCli([], fail=True), out=self.out)
        self.assertEqual(self.out.read_text(), '{"rows": [{"id": 1}]}')
        self.assertEqual(refresh.main(["--out", str(self.out), "--min-age", "0"], run=FakeCli([], fail=True)), 1)
        self.assertEqual(self.out.read_text(), '{"rows": [{"id": 1}]}')
        self.assertEqual([p.name for p in Path(self.dir.name).iterdir()], [".swarph-panel-rows.json"])

    def test_a_fresh_cache_is_not_refreshed_again(self):
        self.out.write_text('{"rows": []}')
        cli = FakeCli([])
        self.assertEqual(refresh.main(["--out", str(self.out), "--min-age", "60"], run=cli), 0)
        self.assertEqual(cli.calls, [])
        self.assertEqual(refresh.main(["--out", str(self.out), "--min-age", "0"], run=cli), 0)
        self.assertEqual(len(cli.calls), 1)

    def test_the_cache_lives_under_the_claude_dir(self):
        with mock.patch.dict("os.environ", {"CLAUDE_CONFIG_DIR": self.dir.name}):
            self.assertEqual(refresh.cache_path(), Path(self.dir.name) / ".swarph-panel-rows.json")


if __name__ == "__main__":
    unittest.main()
